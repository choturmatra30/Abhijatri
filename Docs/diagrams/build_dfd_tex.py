def main() -> None:
    _, rule, _ = run_checks(SHEETS, draw=False)
    assert not (rule or check_tables()), rule
    body = [PREAMBLE]

    # ------------------------------------------------------------------ 1 diagrams
    first = True
    for key, heading, _ in SECTION:
        sheets = [s for s in SHEETS if s.group == key]
        for i, s in enumerate(sheets):
            cap = heading + (f", {s.sheet}" if s.sheet else "")
            body.append(r"\begin{landscape}")
            if first:
                body.append(r"\section{The Diagrams}")
                first = False
            if i == 0:
                body.append(rf"\subsection{{{esc(heading)}}}")
            else:
                body.append(r"\vspace*{2mm}")
            body.append(r"\begin{center}")
            body.append(rf"\includegraphics[width=\linewidth,height=0.84\textheight,keepaspectratio]{{{s.key}.png}}")
            body.append(rf"\captionof{{figure}}{{{esc(cap)}}}\label{{fig:{s.key}}}")
            body.append(r"\end{center}")
            body.append(r"\end{landscape}")

    # ------------------------------------------------------------------ 2 data dictionary
    body.append(r"\section{Data Dictionary}")
    body.append(r"\subsection{External Entities}")
    body.append(longtable(r"L{26mm}L{36mm}L{45mm}L{45mm}", ["Entity", "Who or what it is", "What it gives the system", "What it receives"],
                          ENTITIES, "External entities", "tab:entities"))
    body.append(r"\subsection{Data Stores}")
    rows = []
    for sid, (name, tables) in sorted(STORE_TABLES.items(), key=lambda kv: int(kv[0][1:])):
        first = dfd_data.STORE_FIRST.get(sid, "Level 0") + ("; loaded by the seed migration" if sid == "D1" else "")
        rows.append([sid, name, ", ".join(tables) if tables else "Browser storage, not a database table (prototype)", first])
    body.append(longtable(r"L{10mm}L{30mm}L{79mm}L{33mm}", ["Store", "Name", "Tables or place", "Where first shown"], rows,
                          "Data stores and the tables behind them", "tab:stores"))
    body.append(r"\subsection{Data Flows}")
    body.append(esc("Flow identifiers carry their diagram's prefix (C for context, 0 for level 0, 4 for the level 1 diagram of 4.0, "
                    "4.3 for the level 2 diagram of 4.3), so every identifier is unique. \"Realises\" names the parent diagram's flow "
                    "that a flow is part of."))
    for key, heading, _ in SECTION:
        d = LOGICAL[key]
        fid = ids(key)
        multi = sum(1 for s in SHEETS if s.group == key) > 1

        def realises(f, d=d):
            if not d.parent:
                return ""
            if d.node(f.src).kind == "process" and d.node(f.dst).kind == "process":
                return "(internal)"
            return f.of or f.label

        rows = [[fid[id(f)], sheet_of(f) if multi else "", nm(d, f.src), nm(d, f.dst), f.label + (" (read and write)" if f.both else ""),
                 realises(f)] for f in d.flows]
        head = ["ID", "Sheet", "From", "To", "Data flow", "Realises"]
        widths = [11, 11, 30, 30, 36, 36]
        keep = [i for i in range(6) if (i != 1 or multi) and (i != 5 or d.parent)]
        spare = (163 - 2.85 * len(keep) - sum(widths[i] for i in keep)) / 3
        widths = [w + (spare if i in (2, 3, 4) else 0) for i, w in enumerate(widths)]
        spec = "".join(rf"L{{{widths[i]:.0f}mm}}" for i in keep)
        body.append(longtable(spec, [head[i] for i in keep], [[r[i] for i in keep] for r in rows], f"Data flows: {heading}"))

    # ------------------------------------------------------------------ 3 balancing
    body.append(r"\section{Balancing}")
    body.append("For every parent flow that crosses a decomposed process's boundary, the table lists the child flows that realise it. "
                "No child flow crosses the boundary without realising a parent flow. Level 0 is balanced against the context diagram "
                "in the same way.")
    rows = []
    for child in LOGICAL.values():
        if not child.parent:
            continue
        parent = LOGICAL[child.parent]
        pids = {"0"} if parent.level == "context" else {child.parent_process}
        own = {n.id for n in child.nodes if n.kind == "process"}
        pf = [f for f in parent.flows if (f.src in pids) != (f.dst in pids)]
        cf = [f for f in child.flows if (f.src in own) != (f.dst in own)]
        cid, pidmap = ids(child.key), ids(parent.key)
        for f in pf:
            other = f.dst if f.src in pids else f.src
            direction = "to" if f.src in pids else "from"
            real = [g for g in cf if (g.of or g.label) == f.label and canon(g.dst if g.src in own else g.src) == canon(other)]
            assert real, f
            rows.append([f"Level {child.level}" + (f" of {child.parent_process}" if child.parent_process else ""),
                         pidmap[id(f)] + " " + direction + " " + nm(parent, other).replace(" (traveller without an account)", ""),
                         f.label, "; ".join(f"{cid[id(g)]} {g.label}" for g in real)])
    body.append(longtable(r"L{18mm}L{34mm}L{38mm}L{63mm}", ["Child", "Parent flow", "Parent label", "Child flows that realise it"], rows,
                          "Parent flows and the child flows that realise them", "tab:balance", size=r"\scriptsize"))
    body.append(r"\end{document}")
    OUT.write_text("\n\n".join(body) + "\n", encoding="utf-8")
    print("wrote", OUT, f"({len(rows)} balancing rows)")


if __name__ == "__main__":
    main()
