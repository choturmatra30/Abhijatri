def esc(text: str) -> str:
    out = []
    for ch in text:
        out.append({"&": r"\&", "%": r"\%", "$": r"\$", "#": r"\#", "_": r"\_", "{": r"\{", "}": r"\}", "~": r"\textasciitilde{}",
                    "^": r"\textasciicircum{}", "\\": r"\textbackslash{}", "→": r"$\rightarrow$", "↔": r"$\leftrightarrow$",
                    "–": "--", "—": "---", " ": "~"}.get(ch, ch))
    return "".join(out)


def longtable(spec, head, rows, caption=None, label=None, size=r"\footnotesize"):
    n = len(head)
    h = " & ".join(rf"\hd{{{esc(x)}}}" for x in head) + r" \\"
    cap = rf"\caption{{{esc(caption)}}}" + (rf"\label{{{label}}}" if label else "") + r"\\" if caption else ""
    lines = [r"{" + size + r"\rowcolors{2}{white}{zebra}", rf"\begin{{longtable}}{{{spec}}}", cap, r"\toprule", r"\rowcolor{headfill}" + h, r"\midrule", r"\endfirsthead",
             rf"\multicolumn{{{n}}}{{l}}{{\small\textit{{(continued)}}}}\\", r"\toprule", r"\rowcolor{headfill}" + h, r"\midrule", r"\endhead",
             r"\bottomrule", r"\endlastfoot"]
    for r in rows:
        lines.append(" & ".join(esc(str(c)) for c in r) + r" \\")
    lines += [r"\end{longtable}", "}"]
    return "\n".join(lines)


