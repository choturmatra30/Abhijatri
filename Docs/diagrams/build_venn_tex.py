"""Builds Docs/Abhijatri-Venn-Diagram.tex: the three Venn diagrams with a reading table for each, in the proposal's
LaTeX style (same cover, fonts and soft colours as Abhijatri-DFD.tex; no blue).

Each Venn starts a new page: a short note, the figure, then its table. Tables are not floated and are kept whole, so a table
that does not fit moves to the top of the next page instead of starting at the foot of a page.
Usage: python make_other.py && python build_venn_tex.py && cd .. && pdflatex Abhijatri-Venn-Diagram.tex (twice)
"""

from pathlib import Path

from build_dfd_tex import PREAMBLE, esc

HERE = Path(__file__).resolve().parent
OUT = HERE.parent / "Abhijatri-Venn-Diagram.tex"
FILL = {"built": "okfill", "planned": "nofill", "not": "nofill"}


def head(text: str) -> str:
    """Swap the DFD title-page and header text for the Venn document's."""
    reps = [
        ("Abhijatri: Data Flow Diagrams -- Team ChoturMatra", "Abhijatri: Venn Diagrams -- Team ChoturMatra"),
        ("Generated by Docs/diagrams/build_dfd_tex.py from the diagram data", "Generated by Docs/diagrams/build_venn_tex.py"),
        ("pdftitle={Abhijatri: Data Flow Diagrams}", "pdftitle={Abhijatri: Venn Diagrams}"),
        (r"\fancyhead[L]{\small Abhijatri: Data Flow Diagrams}", r"\fancyhead[L]{\small Abhijatri: Venn Diagrams}"),
        (r"\Large\bfseries\color{accent} Data Flow Diagrams\par", r"\Large\bfseries\color{accent} Venn Diagrams\par"),
        (r"\hd{Document}  & Data flow diagrams: context, level 0, level 1 and level 2, with data dictionary and balancing \\",
         r"\hd{Document}  & Three Venn diagrams: what Abhijatri combines, where it sits among existing tools, and how the team's work overlaps \\"),
        (r"\hd{Notation}  & Gane--Sarson \\", r"\hd{Basis}     & Project proposal and Docs/Implemented.md (what is built) \\"),
        (r"""\tableofcontents
\clearpage
\listoffigures
\clearpage""", r"""\tableofcontents
\vspace{8mm}
\listoffigures
\vspace{8mm}
\listoftables
\clearpage"""),
    ]
    for a, b in reps:
        assert text.count(a) == 1, a
        text = text.replace(a, b)
    extra = r"""\usepackage{float}
\definecolor{okfill}{HTML}{E3F3EA}
\definecolor{partfill}{HTML}{FFF4D6}
\definecolor{nofill}{HTML}{F9E3DC}
"""
    return text.replace(r"\usepackage{graphicx}", extra + r"\usepackage{graphicx}", 1)


def table(caption: str, spec: str, header: list[str], rows: list[list[str]], status_col: int | None = None) -> str:
    out = [r"\begin{table}[H]", r"\centering", rf"\caption{{{esc(caption)}}}", r"\small", r"\rowcolors{2}{white}{zebra}",
           rf"\begin{{tabular}}{{{spec}}}", r"\toprule", r"\rowcolor{headfill}" + " & ".join(rf"\hd{{{esc(h)}}}" for h in header) + r" \\",
           r"\midrule"]
    for r in rows:
        cells = [esc(c) for c in r]
        if status_col is not None:
            key = r[status_col].lower()
            colour = next((v for k, v in FILL.items() if key.startswith(k)), "partfill")
            cells[status_col] = rf"\cellcolor{{{colour}}}" + cells[status_col]
        out.append(" & ".join(cells) + r" \\")
    out += [r"\bottomrule", r"\end{tabular}", r"\end{table}"]
    return "\n".join(out)


def figure(png: str, caption: str, short: str) -> str:
    return "\n".join([r"\begin{figure}[H]", r"\centering",
                      rf"\includegraphics[width=\textwidth,height=0.58\textheight,keepaspectratio]{{{png}}}",
                      rf"\caption[{esc(short)}]{{{esc(caption)}}}", r"\end{figure}"])


def main() -> None:
    body = [head(PREAMBLE)]

    body.append(r"\section{Venn 1: What Abhijatri Combines}")
    body.append(esc("The proposal's problem statement found that travellers in Bangladesh meet these three needs only in separate "
                    "places. Built today: the Bangla interface, moderated reviews and advisory freshness labels. Offline use and "
                    "pricing are a prototype or planned."))
    body.append(figure("venn-product.png",
                       "Venn 1: The Three Traveller Needs That Abhijatri Combines. The sets are Bangla-First, Moderated and Dated, and "
                       "Offline and Priced; each region is marked built, prototype or planned.",
                       "Venn 1: The Three Needs Abhijatri Combines"))
    body.append(table("Venn 1: What Each Region Means", r"L{40mm}L{78mm}L{38mm}", ["Region", "What It Means", "Status"], [
        ["Bangla-First (alone)", "A Bangla default interface, with English selectable", "Built (no automated test of the language switch yet)"],
        ["Moderated and Dated (alone)", "Reviews checked by moderators before they appear; advisories with a source date and a freshness state", "Built and tested"],
        ["Offline and Priced (alone)", "Itemised cost estimates and destination packs that work without a signal", "Prototype screens only"],
        ["Bangla-First and Moderated", "Bangla destination content and reviews shown with their freshness labels", "Built"],
        ["Bangla-First and Offline", "Bangla pages readable without a connection", "Planned (no service worker or IndexedDB yet)"],
        ["Moderated and Priced", "Estimates built from prices that carry a source and a date", "Planned with the price catalogue"],
        ["All three: Abhijatri", "A Bangla-first, moderated and priced trip guide that works offline", "The project goal; partly built"],
    ], status_col=2))

    body.append(r"\clearpage")
    body.append(r"\section{Venn 2: Where Abhijatri Sits Among Existing Tools}")
    body.append(esc("The circles are capabilities, not products. Each kind of tool sits in the one region it covers well. This is general "
                    "positioning from the proposal, not a market study: no product is named and no figures are claimed. Abhijatri aims "
                    "for the centre; its offline part is still planned, so the centre says so."))
    body.append(figure("venn-landscape.png",
                       "Venn 2: Existing Travel Tools and Where Abhijatri Sits. Each kind of tool covers one capability; Abhijatri aims "
                       "for the centre. "
                       "No kind of tool compared covers two or more capabilities.",
                       "Venn 2: Existing Travel Tools and Where Abhijatri Sits"))
    body.append(table("Venn 2: Kinds of Tools in Each Region", r"L{40mm}L{50mm}L{66mm}", ["Region", "Kind of Tool", "Why It Sits There"], [
        ["Bangla-First only", "Social media travel groups and blogs", "Bangla and local knowledge, but posts are not moderated or dated"],
        ["Moderated and Dated only", "Booking and guide sites", "Checked listings and reviews, mostly in English and online only"],
        ["Works Offline only", "Maps and offline apps", "Work without a signal, but carry little local travel advice and no trip costs"],
        ["Any two capabilities", "None of the tool types compared", "This gap is the problem the proposal describes"],
        ["All three", "Abhijatri", "Bangla-first and moderated parts built; offline planned"],
    ]))

    body.append(r"\clearpage")
    body.append(r"\section{Venn 3: Team Responsibilities}")
    body.append(esc("The centre covers scope, destination content, estimator rules (planned), integration and documents. The table gives "
                    "the same information in responsible-and-accountable form."))
    body.append(figure("venn-roles.png",
                       "Venn 3: Team Responsibilities and Shared Work. The three specialist roles in Team ChoturMatra and the work they "
                       "share; the centre is the project leader's coordination role, not a fourth set.",
                       "Venn 3: Team Responsibilities and Shared Work"))
    body.append(table("Venn 3: Shared Work by Role", r"L{80mm}L{44mm}L{32mm}", ["Shared Work", "Responsible", "Accountable"], [
        ["API contract and error handling", "Frontend and Backend", "Leader"],
        ["Offline and real-device tests", "Frontend and Quality", "Leader"],
        ["Integration and security tests", "Backend and Quality", "Leader"],
        ["Scope, destination content, estimator rules (planned), documents", "Leader", "Leader"],
        ["End-to-end review flow", "All three", "Leader"],
    ]))
    body.append(esc("Roles: Frontend and offline, Abdullah Bin Sorwar Choudhury; Backend and data, Syed Muhtasim Alam; Quality "
                    "assurance, Md. Irfan Iqbal; Project leader, Shahriar Islam."))
    body.append(r"\end{document}")
    OUT.write_text("\n\n".join(body) + "\n", encoding="utf-8")
    print("wrote", OUT)


if __name__ == "__main__":
    main()
