def table(caption: str, widths: list[float], header: list[str], rows: list[list[str]], size: str = r"\small",
          bold_first: bool = False, page_w: float = TEXT_W) -> str:
    """A longtable whose start is protected: if the whole table fits on a page it is kept together."""
    avail = page_w - 1.0 - len(widths) * 8 / 2.845  # tabcolsep is 4pt on each side of every column
    widths = [w * avail / sum(widths) for w in widths]  # columns always fill the text width exactly
    scale = {r"\small": 1.6, r"\footnotesize": 1.45}[size]  # average character width in mm (Times)
    line_h = {r"\small": 4.9, r"\footnotesize": 4.4}[size]
    est = 18.0
    for r in [header] + rows:
        lines = max(sum(max(1, math.ceil(len(part) * scale / max(w - 2.5, 5))) for part in str(c).split("\n")) for c, w in zip(r, widths))
        est += lines * line_h + 1.2
    need = est if est < 215 else 110
    spec = "".join(rf"L{{{w:.1f}mm}}" for w in widths)
    n = len(header)
    h = r"\rowcolor{headfill}" + " & ".join(rf"\hd{{{esc(x)}}}" for x in header) + r" \\"
    out = [rf"\Needspace*{{{need:.0f}mm}}", r"{" + size + r"\rowcolors{2}{white}{zebra}", rf"\begin{{longtable}}{{{spec}}}",
           rf"\caption{{{esc(caption)}}}\\", r"\toprule", h, r"\midrule", r"\endfirsthead",
           rf"\multicolumn{{{n}}}{{l}}{{\small\textit{{(continued)}}}}\\", r"\toprule", h, r"\midrule", r"\endhead",
           r"\bottomrule", r"\endlastfoot"]
    for r in rows:
        cells = []
        for i, c in enumerate(r):
            t = r" \newline ".join(esc(p) for p in str(c).split("\n"))
            t = t.replace(r"\_", r"\_\allowbreak{}")
            cells.append(rf"\textbf{{{t}}}" if bold_first and i == 0 else t)
        out.append(" & ".join(cells) + r" \\")
    out += [r"\end{longtable}", "}"]
    return "\n".join(out)


def p(text: str) -> str:
    return esc(text)


def bullets(items: list[str]) -> str:
    return "\\begin{itemize}\n" + "\n".join(r"\item " + esc(i) for i in items) + "\n\\end{itemize}"


def land_figure(png: str, caption: str, short: str, height: str = r"0.80\textheight", before: str = "") -> str:
    # \afterpage: the landscape page is inserted at the next page break, so the text keeps filling the current page
    return "\n".join([r"\afterpage{\begin{landscape}", before, r"\begin{center}",
                      rf"\includegraphics[width=\linewidth,height={height},keepaspectratio]{{{png}}}",
                      rf"\captionof{{figure}}[{esc(short)}]{{{esc(caption)}}}", r"\end{center}", r"\end{landscape}}"])


def portrait_figure(png: str, caption: str, short: str, height: str = r"0.42\textheight") -> str:
    return "\n".join([r"\begin{center}", rf"\includegraphics[width=\linewidth,height={height},keepaspectratio]{{{png}}}",
                      rf"\captionof{{figure}}[{esc(short)}]{{{esc(caption)}}}", r"\end{center}"])


def note(text: str) -> str:
    """A figure note in a dashed, sand-coloured box, set apart from the body text."""
    return r"\begin{notebox}{\color{notehead}\bfseries Note.} " + esc(text) + r"\end{notebox}"


def uc(title: str, rows: list[list[str]]) -> str:
    return table(title, [34, 123.5], ["Field", "Specification"], rows, bold_first=True)


def keep_heading_with_table(blocks: list[str]) -> list[str]:
    """Move a table's space check in front of the heading (and short paragraph) above it, so no heading is left
    alone at the foot of a page while its table moves on."""
    heads = (r"\section", r"\subsection", r"\subsubsection")
    out = list(blocks)
    for i, blk in enumerate(out):
        m = re.match(r"\\Needspace\*\{(\d+)mm\}\n", blk)
        if not m:
            continue
        need = int(m.group(1))
        j, extra = i - 1, 12
        if j >= 0 and not out[j].startswith(heads) and not out[j].startswith("\\") and j - 1 >= 0 and out[j - 1].startswith(heads):
            extra += 6 + len(out[j]) // 18  # the paragraph between heading and table (about 18 characters per mm of height)
            j -= 1
        if j >= 0 and out[j].startswith(heads):
            out[i] = blk[m.end():]
            out[j] = rf"\Needspace*{{{min(need + extra, 230)}mm}}" + "\n" + out[j]
    return out


